import assert from 'node:assert/strict';
import {outcome,train,vector,historicalEvidence} from './fast-learning.mjs';
const t=1800000000000,start=t+60000;
const r={status:'sent',sentAt:new Date(t+20000).toISOString(),entry:100,side:'LONG',sweepConfirmation:{volumeRatio:3,recovery:.7,shockFlow:.7,reversalFlow:.8}};
const rows=Array.from({length:6},(_,i)=>[t+i*60000,100,i===0?500:102,99,101,0,t+i*60000+59999]);
assert.equal(outcome(r,rows,5,start+300000-1),null);
assert.equal(outcome(r,rows.slice(1,4),5,start+300000),null);
const result=outcome(r,rows,5,start+300000);
assert.ok(Math.abs(result.favorablePct-2)<1e-8);
assert.ok(Math.abs(result.directionalClosePct-1)<1e-8);
assert.ok(Math.abs(outcome({...r,side:'SHORT'},rows,5,start+300000).directionalClosePct+1)<1e-8);
assert.equal(vector({...r,sweepConfirmation:{}}),null);
assert.equal(train({},t),null);
const records=Object.fromEntries(Array.from({length:40},(_,i)=>[i,{...r,sentAt:new Date(t+i*600000).toISOString(),outcomes:{5:{maturedAt:t+i*600000+360000,directionalClosePct:i%2?1:-1}}}]));
const model=train(records,t+40*600000);
assert.equal(model.trainingCount,40);assert.equal(model.affectsLiveSelection,false);assert.equal(model.temporalTest.n,10);
assert.ok(Number.isFinite(model.temporalTest.brier));
assert.equal(train(records,t+600000),null);
const past={...r,id:'past',provider:'binance-futures',strategyVersion:'fast-reversal-v1',outcomes:{5:{...result,maturedAt:start+300000,directionalClosePct:-1},30:{...result,maturedAt:start+1800000,directionalClosePct:3}}};
const evidence=historicalEvidence({past,short:{...past,side:'SHORT'},future:{...past,sentAt:new Date(t+86400000).toISOString()}},'LONG',start+300000);
assert.equal(evidence.horizons[5].count,1);
assert.equal(evidence.horizons[5].nonPositiveClose,1);
assert.equal(evidence.horizons[30].count,0);
assert.equal(evidence.recentCases[0].outcomes[30],undefined);
console.log('Fast learning passed: no partial-minute leakage, maturity, missing bars, both sides and chronological holdout');
