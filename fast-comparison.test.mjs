import assert from 'node:assert/strict';
import {compare,wilson,report} from './fast-comparison.mjs';
const start=1800000000000,day=86400000;
const row=(i,pass=false)=>({id:String(i),symbol:'C'+i,side:i%2?'SHORT':'LONG',provider:'binance-futures',cohort:'prospective_candidate',status:'observed',observedAt:new Date(start+i*day/5).toISOString(),initialAssessment:{pass,reason:pass?undefined:'opposing_btc_trend',btcContextChallenger:{pass:true}},outcomes:Object.fromEntries([5,30,240].map(m=>[m,{maturedAt:start+i*day/5+m*60000,directionalClosePct:i%2?1:-1,favorablePct:2,adversePct:-1}]))});
const rows=Object.fromEntries(Array.from({length:100},(_,i)=>[i,row(i)]));
const now=start+21*day;
const c=compare(rows,now);
assert.equal(c.status,'collecting_holdout');assert.equal(c.discovery.maturedCases,100);assert.equal(c.results[5].netPositive,50);assert.equal(c.added.bySide.LONG[5].netPositive,0);assert.equal(c.added.bySide.SHORT[5].netPositive,50);
assert.equal(c.affectsLiveSelection,false);assert.ok(report(c).includes('100/100'));
const d=compare({...rows,duplicate:{...row(0),id:'other',side:'SHORT',observedAt:new Date(start+60000).toISOString()},old:{...row(111),cohort:'retrospective'}},now,c);
assert.equal(d.excludedOverlapping,1);assert.equal(d.rawEligible,101);assert.equal(d.frozenAt,c.frozenAt);
assert.equal(compare(rows,start+day).status,'collecting_discovery');
assert.equal(compare({a:row(0,true),b:row(1)},now).baseline.count,1);
assert.equal(compare({a:row(0,true),b:row(1)},now).challenger.count,2);
const extended={...rows,...Object.fromEntries(Array.from({length:50},(_,i)=>[i+110,row(i+110)]))};
assert.equal(compare(extended,start+33*day,c).status,'ready_for_review');
assert.equal(compare(extended,start+33*day,c).heldOutAdded.count,50);
assert.equal(wilson(0,0),null);assert.ok(wilson(0,100)[1]>0);assert.ok(wilson(100,100)[0]<1);
console.log('BTC comparison passed: same cohort, overlap exclusion, sides, costs, maturity, frozen future holdout, no live promotion');
